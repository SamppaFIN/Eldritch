/**
 * The Härmälä map drawn in Claude Design → the game's own hexes (BRDC-WORLD-001).
 *
 * The design (`packages/core/src/data/seed/harmala.design.json`) is a pointy-top hex grid
 * laid on a satellite image, in two sizes, with lat/lng *estimated* from the image. Its
 * Statue of the Boy sits ≈110 m from the real one, so the whole design is shifted by that
 * offset first (Infinite 2026-10-14 gave the statue's exact place). One point fixes the
 * offset only; `SCALE` stays 1 until a second, distant point is known.
 *
 * Then every H3 res-11 cell over the area takes the terrain of the nearest design hex —
 * a fine one if one is close enough, else a coarse one — and the result is written as one
 * row per res-10 parent: its seven children's terrain letters, in `cellToChildren` order.
 *
 *   node scripts/gen-harmala.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { createRequire } from 'node:module';

// h3-js is `packages/core`'s dependency, not the root's.
const { cellToChildren, cellToLatLng, latLngToCell, polygonToCells } = createRequire(join(process.cwd(), 'packages/core/package.json'))('h3-js');

const seedDir = join(process.cwd(), 'packages/core/src/data/seed');
const design = JSON.parse(readFileSync(join(seedDir, 'harmala.design.json'), 'utf8'));

/** The statue as the design drew it, and where it really stands (Infinite 2026-10-14). */
const DESIGN_STATUE = design.pois.find((p) => p.name === 'Statue of the Boy');
const REAL_STATUE = { lat: 61.472883311234405, lng: 23.726056773550532 };
const SCALE = 1;
const shift = (p) => ({
  lat: REAL_STATUE.lat + (p.lat - DESIGN_STATUE.lat) * SCALE,
  lng: REAL_STATUE.lng + (p.lng - DESIGN_STATUE.lng) * SCALE,
});

/** Hex radii from the design's own metadata: r10 16.5 px, r11 6.25 px at 4 m/px. */
const REACH_M = { 11: 6.25 * 4, 10: 16.5 * 4 };
const LETTER = { plain: 'p', forest: 'f', hill: 'h', mountain: 'm', lake: 'l', coast: 'c', market: 'k', marsh: 's', settlement: 'v' };

const hexes = design.hexes.map((h) => ({ ...h, ...shift(h) }));
const M_LAT = 111_320;
const mLng = (lat) => M_LAT * Math.cos((lat * Math.PI) / 180);
const dist = (a, b) => Math.hypot((a.lat - b.lat) * M_LAT, (a.lng - b.lng) * mLng(a.lat));

// A coarse bucket grid so each lookup checks only nearby design hexes.
const BUCKET = 0.002;
const key = (lat, lng) => `${Math.floor(lat / BUCKET)}:${Math.floor(lng / BUCKET)}`;
const buckets = new Map();
for (const h of hexes) {
  const k = key(h.lat, h.lng);
  if (!buckets.has(k)) buckets.set(k, []);
  buckets.get(k).push(h);
}
function nearest(p, res) {
  let best = null;
  let bestD = Infinity;
  const bi = Math.floor(p.lat / BUCKET);
  const bj = Math.floor(p.lng / BUCKET);
  for (let i = bi - 1; i <= bi + 1; i += 1) {
    for (let j = bj - 1; j <= bj + 1; j += 1) {
      for (const h of buckets.get(`${i}:${j}`) ?? []) {
        if (h.res !== res) continue;
        const d = dist(p, h);
        if (d < bestD) [best, bestD] = [h, d];
      }
    }
  }
  return best && bestD <= REACH_M[res] ? best : null;
}

const lats = hexes.map((h) => h.lat);
const lngs = hexes.map((h) => h.lng);
const box = [
  [Math.min(...lats), Math.min(...lngs)],
  [Math.min(...lats), Math.max(...lngs)],
  [Math.max(...lats), Math.max(...lngs)],
  [Math.max(...lats), Math.min(...lngs)],
];
const parents = new Set(polygonToCells(box, 11).map((c) => latLngToCell(...cellToLatLng(c), 10)));

const rows = {};
let cells = 0;
for (const parent of [...parents].sort()) {
  const letters = cellToChildren(parent, 11).map((c) => {
    const [lat, lng] = cellToLatLng(c);
    const h = nearest({ lat, lng }, 11) ?? nearest({ lat, lng }, 10);
    if (h) cells += 1;
    return h ? LETTER[h.terrain] : '.';
  });
  if (letters.some((l) => l !== '.')) rows[parent] = letters.join('');
}

const out = {
  v: 1,
  note: 'Generated by scripts/gen-harmala.mjs from harmala.design.json — do not edit by hand.',
  shift: { lat: REAL_STATUE.lat - DESIGN_STATUE.lat, lng: REAL_STATUE.lng - DESIGN_STATUE.lng, scale: SCALE },
  letters: LETTER,
  rows,
};
writeFileSync(join(seedDir, 'harmala.design-terrain.json'), `${JSON.stringify(out)}\n`, 'utf8');
console.log(`${Object.keys(rows).length} res-10 rows, ${cells} res-11 cells with terrain; shift ${(out.shift.lat * M_LAT).toFixed(1)} m N, ${(out.shift.lng * mLng(REAL_STATUE.lat)).toFixed(1)} m E`);
